test('minimum shuffle gate cannot be bypassed and cannot pick before Finish Shuffling',()=>{
 let s=createRitualSession();
 assert.throws(()=>transitionRitual(s,'CONFIRM_THREE'),/Illegal/);
 const preflight=prepareQuestionPreflight({question:'Should I change jobs?'});
 assert.equal(preflight.intent,'career');assert.equal(preflight.summaryReady,false);
 s=transitionRitual(s,'SUBMIT_QUESTION',{question:'Should I change jobs?',preflight},100);
 assert.equal(s.phase,'question_submitted');
 assert.throws(()=>buildLockedMainReadingRequest(s,'request-1'),/before three cards/);
 s=transitionRitual(s,'COLLAPSE_COMPLETE',{},1000);
 assert.equal(s.phase,'shuffle_ritual');
 assert.throws(()=>transitionRitual(s,'MIN_SHUFFLE_ELAPSED',{},1000+MIN_SHUFFLE_MS-1),/minimum duration/);
 assert.throws(()=>transitionRitual(s,'TOGGLE_CARD',{cardId:'major-00',orientation:'upright'},1002),/Illegal/);
 s=transitionRitual(s,'MIN_SHUFFLE_ELAPSED',{},1000+MIN_SHUFFLE_MS);
 s=transitionRitual(s,'FINISH_SHUFFLING',{},9000);
 assert.equal(s.phase,'sphere_selection');
});
test('three picked cards remain reversible until an idempotent immutable lock',()=>{
 let s=createRitualSession();
 s=transitionRitual(s,'SUBMIT_QUESTION',{question:'How should I move forward?'},0);
 s=transitionRitual(s,'COLLAPSE_COMPLETE',{},1000);
 s=transitionRitual(s,'MIN_SHUFFLE_ELAPSED',{},6500);
 s=transitionRitual(s,'FINISH_SHUFFLING',{},6600);
 s=transitionRitual(s,'TOGGLE_CARD',{cardId:'major-00',orientation:'reversed'});
 s=transitionRitual(s,'TOGGLE_CARD',{cardId:'cups-02',orientation:'upright'});
 assert.equal(s.selected.length,2);assert.equal(canConfirmThree(s),false);
 s=transitionRitual(s,'TOGGLE_CARD',{cardId:'cups-02',orientation:'reversed'});
 assert.equal(s.selected.length,1);
 s=transitionRitual(s,'TOGGLE_CARD',{cardId:'cups-02',orientation:'upright'});
 s=transitionRitual(s,'TOGGLE_CARD',{cardId:'major-09',orientation:'upright'});
 assert.equal(canConfirmThree(s),true);
 assert.throws(()=>transitionRitual(s,'TOGGLE_CARD',{cardId:'major-18',orientation:'upright'}),/no more than three/);
 const locked=transitionRitual(s,'CONFIRM_THREE',{},19000);
 assert.equal(locked.phase,'three_locked');
 assert.strictEqual(transitionRitual(locked,'CONFIRM_THREE',{},19001),locked);
 assert.deepEqual(locked.locked.map(x=>x.positionId),['past','present','future']);
 assert.equal(locked.locked[0].orientation,'reversed');
 assert.throws(()=>transitionRitual(locked,'TOGGLE_CARD',{cardId:'major-00',orientation:'upright'}),/Illegal/);
 const req=buildLockedMainReadingRequest(locked,'req-abc');
 assert.equal(req.cards[2].cardId,'major-09');
 assert.equal(req.cards[0].position,'past');
 s=transitionRitual(locked,'VORTEX_COMPLETE');
 assert.equal(s.phase,'three_reveal');
 assert.throws(()=>transitionRitual(s,'ALL_REVEALED'),/All three/);
 for(let i=0;i<3;i++)s=transitionRitual(s,'REVEAL_CARD',{index:i});
 s=transitionRitual(s,'ALL_REVEALED');
 s=transitionRitual(s,'INVITE_READER');
 assert.equal(s.phase,'main_reading');
});
test('guidance binds NEW card and carries original three-card context',()=>{
 let s=createRitualSession();
 s=transitionRitual(s,'SUBMIT_QUESTION',{question:'Where am I heading?'});
 s=transitionRitual(s,'COLLAPSE_COMPLETE',{},1000);
 s=transitionRitual(s,'MIN_SHUFFLE_ELAPSED',{},7000);
 s=transitionRitual(s,'FINISH_SHUFFLING');
 for(const id of ['major-00','cups-02','major-09'])s=transitionRitual(s,'TOGGLE_CARD',{cardId:id,orientation:'upright'});
 s=transitionRitual(s,'CONFIRM_THREE');
 s=transitionRitual(s,'VORTEX_COMPLETE');
 for(let i=0;i<3;i++)s=transitionRitual(s,'REVEAL_CARD',{index:i});
 s=transitionRitual(s,'ALL_REVEALED');
 s=transitionRitual(s,'INVITE_READER');
 s=transitionRitual(s,'START_GUIDANCE');
 s=transitionRitual(s,'SUBMIT_GUIDANCE_QUESTION',{question:'What should I clarify?'});
 assert.throws(()=>transitionRitual(s,'LOCK_GUIDANCE_CARD',{cardId:'major-00',orientation:'upright'}),/must be new/);
 s=transitionRitual(s,'LOCK_GUIDANCE_CARD',{cardId:'wands-07',orientation:'reversed'});
 const context=buildGuidanceContext(s,s.guidanceQuestion,'req2','My main reading connects the earlier choices.');
 assert.equal(context.originalThree.length,3);
 assert.equal(context.guidanceCard.cardId,'wands-07');
 assert.equal(transitionRitual(s,'REVEAL_GUIDANCE').phase,'guidance_reading');
});
